function selectedEmployers() {
  const boxes = [...document.querySelectorAll("#employer-filters input")];
  if (!boxes.length) return null;
  const on = boxes.filter((el) => el.checked).map((el) => el.value);
  if (!on.length || on.length === boxes.length) return null;
  return new Set(on);
}

function applyFilters(jobs) {
  const q = ($("search") && $("search").value.trim().toLowerCase()) || "";
  const urgency = new Set(checkedValues("urgency"));
  const location = new Set(checkedValues("location"));
  const tracks = new Set(checkedValues("track"));
  const notifiedEl = document.querySelector("input[name=notified]:checked");
  const notified = notifiedEl ? notifiedEl.value : "any";
  const myJobsEl = document.querySelector("input[name=myjobs]:checked");
  const myJobs = myJobsEl ? myJobsEl.value : "all";
  const employers = selectedEmployers();
  return jobs.filter((job) => {
    if (urgency.size && !urgency.has(job.urgency)) return false;
    if (location.size && !location.has(job.location_label)) return false;
    if (tracks.size && !(job.tracks || []).some((tr) => tracks.has(tr))) return false;
    if (notified === "yes" && !job.notified) return false;
    if (notified === "no" && job.notified) return false;
    if (myJobs === "interested" || myJobs === "applied") {
      if (getJobStatus(state.tracker, job.web_sifra) !== myJobs) return false;
    }
    if (employers && !employers.has(job.employer || "(unknown)")) return false;
    if (!q) return true;
    const blob = [
      job.title,
      job.title_en,
      displayTitle(job),
      job.employer,
      job.matched_keywords,
      job.shortage_occupations,
      job.location_raw,
      job.web_sifra,
    ]
      .join(" ")
      .toLowerCase();
    return blob.includes(q);
  });
}

function sortJobs(jobs) {
  const sortEl = $("sort");
  const mode = sortEl ? sortEl.value : "deadline";
  const copy = [...jobs];
  copy.sort((a, b) => {
    if (mode === "title") {
      return displayTitle(a).localeCompare(displayTitle(b), state.lang === "hr" ? "hr" : "en");
    }
    if (mode === "score") return (b.foreign_score || 0) - (a.foreign_score || 0);
    if (mode === "newest") return (b.first_seen_at || "").localeCompare(a.first_seen_at || "");
    const ad = a.deadline_date || "9999-12-31";
    const bd = b.deadline_date || "9999-12-31";
    return ad.localeCompare(bd);
  });
  return copy;
}

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

const HR_LOCALE = "hr";
const COMPANY_SUFFIX_RE = /^(j\.d\.o\.o\.?|d\.o\.o\.?|d\.d\.?)$/i;

function lettersOf(text) {
  return String(text).match(/\p{L}/gu) || [];
}

function isUpperLetter(ch) {
  return ch === ch.toLocaleUpperCase(HR_LOCALE) && ch !== ch.toLocaleLowerCase(HR_LOCALE);
}

function isLowerLetter(ch) {
  return ch === ch.toLocaleLowerCase(HR_LOCALE) && ch !== ch.toLocaleUpperCase(HR_LOCALE);
}

function isAllCapsField(text) {
  const letters = lettersOf(text);
  if (letters.length < 2) return false;
  const upper = letters.filter(isUpperLetter).length;
  return upper / letters.length >= 0.8;
}

function isAbbreviationToken(token) {
  // Company suffixes stay as written: d.o.o / d.o.o. / j.d.o.o. / d.d.
  if (COMPANY_SUFFIX_RE.test(token)) return true;
  const letters = lettersOf(token);
  const letterCount = letters.length;
  // Abbreviation: 2–5 letters, all caps, no lowercase (VPR, HZZ, EU, USA)
  if (letterCount < 2 || letterCount > 5) return false;
  if (letters.some(isLowerLetter)) return false;
  return letters.every(isUpperLetter);
}

function titleCaseSegment(segment) {
  if (!segment) return segment;
  if (isAbbreviationToken(segment)) return segment;
  const letters = lettersOf(segment);
  if (letters.length <= 1) return segment;
  let seenLetter = false;
  return [...segment]
    .map((ch) => {
      if (!/\p{L}/u.test(ch)) return ch;
      if (!seenLetter) {
        seenLetter = true;
        return ch.toLocaleUpperCase(HR_LOCALE);
      }
      return ch.toLocaleLowerCase(HR_LOCALE);
    })
    .join("");
}

function titleCaseToken(token) {
  return token.split("-").map(titleCaseSegment).join("-");
}

// Display-only ALL CAPS → Title Case. Does not mutate jobs.json.
//   ZDRAVSTVENA USTANOVA → Zdravstvena Ustanova
//   VPR EVENTS → VPR Events (VPR 3-letter acronym, EVENTS title-cased)
//   Acme d.o.o. unchanged if not ALL CAPS
function toDisplayCase(value) {
  const text = String(value ?? "");
  if (!isAllCapsField(text)) return text;
  return text
    .split(/(\s+)/)
    .map((part) => (/^\s+$/.test(part) ? part : titleCaseToken(part)))
    .join("");
}

function tipSpan(className, label, tipKey) {
  const tip = t(tipKey);
  return `<span class="${className} has-tip" data-tip="${escapeHtml(tip)}" title="${escapeHtml(tip)}">${escapeHtml(label)}</span>`;
}

function keywordPills(job) {
  const raw = job.matched_keywords || "";
  return raw
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean)
    .map((kw) => tipSpan("badge muted-pill", kw, "tipKeyword"))
    .join("");
}

