function initSync() {
  if (!GOOGLE_CLIENT_ID) {
    renderSync();
    return;
  }
  if (isInAppBrowser()) {
    sync.status = "inapp";
  } else if (readFlag(SYNC_FLAG_KEY)) {
    sync.status = "resume";
    loadGis().catch(() => {});
  } else {
    sync.status = "off";
    if (readFlag(SYNC_INTRO_KEY)) loadGis().catch(() => {});
  }
  renderSync();
  document.addEventListener("visibilitychange", () => {
    if (document.visibilityState === "visible" && hasValidToken()) runSync();
  });
}

